export type DirectionId = "automation" | "landing" | "content";

export interface Direction {
  id: DirectionId;
  /** Как направление называется в интерфейсе */
  title: string;
  /** Короткое описание для карточки выбора */
  blurb: string;

  /** Нижняя граница вилки: с этого можно начинать брать, USD */
  priceFrom: number;
  /** Приписка к вилке. Потолка не ставим, он открытый */
  priceNote: string;
  /** Как звучит ориентир рынка. Формулировка «от и выше», не фиксированная цена */
  marketLine: string;

  /**
   * Лесенка чеков по возрастанию. Чем выше цель человека, тем крупнее берём
   * проект, а не тем больше набираем мелких заказов.
   */
  tiers: PriceTier[];
  /** Что человек будет создавать */
  deliverable: string;
  /** Как выглядит AI-процесс, по шагам */
  process: string[];
  /** Примеры результата */
  examples: string[];
  /** Пакет программы Академии, который закрывает это направление */
  coursePackage: CoursePackage;
  /** Шаги пути к первой $1000 */
  path: string[];
}

export interface PriceTier {
  /** Чек за один проект, USD */
  price: number;
  /** Что это за проект по объёму */
  label: string;
}

export interface CoursePackage {
  /** Номер пакета в программе */
  number: number;
  /** Название пакета как на сайте курса */
  name: string;
  /** Модули пакета */
  modules: string[];
  /**
   * Цена участия. Пока не проставлена: сетка Потока II ($397 / $647 / $1499 / $2999)
   * устарела, актуальную ждём от Влада. Как только придёт, ставим сюда и в UI
   * появляются кнопка и цена. FIXME(pricing)
   */
  price: number | null;
  /** Куда ведёт кнопка перехода на пакет. FIXME(pricing) */
  url: string | null;
}

/** Цель по умолчанию, если человек ещё не ответил. */
export const targetAmount = 1000;

/** Больше этого числа заказов показывать бессмысленно, это читается как галера. */
const MAX_PROJECTS = 4;

export interface Plan {
  tier: PriceTier;
  count: number;
  total: number;
}

/**
 * Подбираем самый доступный чек, при котором до цели остаётся не больше
 * четырёх проектов. Если цель большая, поднимаемся по лесенке вверх.
 */
export function planForTarget(id: DirectionId, target: number): Plan {
  const tiers = directions[id].tiers;
  const fit =
    tiers.find((t) => Math.ceil(target / t.price) <= MAX_PROJECTS) ??
    tiers[tiers.length - 1];
  const count = Math.max(1, Math.ceil(target / fit.price));
  return { tier: fit, count, total: count * fit.price };
}

export function projectsForTarget(id: DirectionId, target: number): number {
  return planForTarget(id, target).count;
}

export function totalForTarget(id: DirectionId, target: number): number {
  return planForTarget(id, target).total;
}

/** Склонение слова «проект» под любое число. */
export function pluralProjects(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return "проектов";
  if (mod10 === 1) return "проект";
  if (mod10 >= 2 && mod10 <= 4) return "проекта";
  return "проектов";
}

