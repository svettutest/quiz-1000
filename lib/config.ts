/**
 * Единственный источник правды по продукту.
 * Названия, цены и количество проектов меняются здесь и нигде больше.
 */

export type DirectionId = "automation" | "landing" | "content";

export interface Direction {
  id: DirectionId;
  /** Как направление называется в интерфейсе */
  title: string;
  /** Короткое описание для карточки выбора */
  blurb: string;
  /** Ориентировочная стоимость одного проекта или пакета, USD */
  examplePrice: number;
  /** Сколько таких проектов складываются в цель */
  projectsForGoal: number;
  /** Подпись под ценой на экране денежного aha */
  priceCaption: string;
  /** Что человек будет создавать */
  deliverable: string;
  /** Как выглядит AI-процесс, по шагам */
  process: string[];
  /** Что необходимо научиться делать человеку */
  humanSkills: string[];
  /** Примеры результата */
  examples: string[];
  /** Чему учится ученик внутри программы */
  curriculum: string[];
  /** Шаги пути к первой $1000 */
  path: string[];
}

